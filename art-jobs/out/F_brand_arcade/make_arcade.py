def hex_rgba(h):
    return (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255)


def render(frame):
    sub = FRAMES[frame]
    assert len(MAP) == 64 and all(len(r) == 32 for r in MAP), "map must be 32 x 64"
    im = Image.new("RGBA", (32, 64), (0, 0, 0, 0))
    for y, row in enumerate(MAP):
        for x, ch in enumerate(row):
            ch = sub.get(ch, ch)
            if ch != ".":
                im.putpixel((x, y), hex_rgba(BASE[ch]))
    return im


def town_composite(idle, active):
    """Sprite at its real in-game size (1 tile wide) on a crop of the tileset,
    the whole scene then shown at 2x nearest-neighbor so the match can be judged."""
    tiles = Image.open(TILESET).convert("RGBA")
    grass = tiles.crop((200, 196, 232, 228))            # plain grass, 32 x 32
    scene = Image.new("RGBA", (264, 148), (0, 0, 0, 255))
    for ty in range(0, scene.height, 32):
        for tx in range(0, scene.width, 32):
            scene.paste(grass, (tx, ty))
    shop = tiles.crop((476, 510, 646, 646))             # red-roof shop for scale
    scene.alpha_composite(shop, (6, 6))
    for i, spr in enumerate((idle, active)):
        scene.alpha_composite(spr, (186 + i * 38, 142 - 64))
    return scene.resize((scene.width * 2, scene.height * 2), Image.NEAREST)


def main():
    idle, active = render("idle"), render("active")
    colors = {p for im in (idle, active) for p in getattr(im, "get_flattened_data", im.getdata)() if p[3]}
    assert len(colors) <= 16, f"{len(colors)} colors"
    assert {p[3] for im in (idle, active) for p in getattr(im, "get_flattened_data", im.getdata)()} <= {0, 255}
    active.save(os.path.join(HERE, "arcade_32x64.png"))
    active.resize((256, 512), Image.NEAREST).save(os.path.join(HERE, "arcade_32x64_x8.png"))
    sheet = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    sheet.paste(idle, (0, 0))
    sheet.paste(active, (32, 0))
    sheet.save(os.path.join(HERE, "arcade_sheet_64x64.png"))
    town_composite(idle, active).save(os.path.join(HERE, "arcade_in_town.png"))
    print(f"ok: {len(colors)} colors")


if __name__ == "__main__":
    main()
